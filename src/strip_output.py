"""Git clean filter for notebooks: what gets committed is code only.

Outputs are regenerated by rerunning the notebook, and they make a notebook
unreviewable in git: plots are base64 blobs that change on every run, and even
text output churns enough to bury the code change in a diff. The markdown
cells carry the explanation, so the committed notebook still reads top to
bottom. Only the committed copy is stripped; the notebook on disk keeps its
outputs.

Enabled once per clone (see "Install" in README.md); .gitattributes applies it.
"""
import json
import sys


def strip(nb: dict) -> dict:
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        cell["outputs"] = []
        cell["execution_count"] = None
        cell.get("metadata", {}).pop("execution", None)   # run timestamps written by nbclient
    return nb


if __name__ == "__main__":
    nb = json.loads(sys.stdin.buffer.read().decode("utf-8"))
    text = json.dumps(strip(nb), indent=1, ensure_ascii=False) + "\n"
    sys.stdout.buffer.write(text.encode("utf-8"))
